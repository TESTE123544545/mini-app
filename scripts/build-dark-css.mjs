// ---- colour maths ---------------------------------------------------------
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
function parse(tok) {
  let m;
  if ((m = /^#([0-9a-f]{3,8})$/i.exec(tok))) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = h.split("").map((c) => c + c).join("");
    if (h.length !== 6 && h.length !== 8) return null;
    return { r: parseInt(h.slice(0, 2), 16), g: parseInt(h.slice(2, 4), 16), b: parseInt(h.slice(4, 6), 16), a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1 };
  }
  if ((m = /^rgba?\(\s*([\d.]+)[\s,]+([\d.]+)[\s,]+([\d.]+)(?:\s*[,/]\s*([\d.]+%?))?\s*\)$/i.exec(tok))) {
    const a = m[4] === undefined ? 1 : m[4].endsWith("%") ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
    return { r: +m[1], g: +m[2], b: +m[3], a };
  }
  if (/^white$/i.test(tok)) return { r: 255, g: 255, b: 255, a: 1 };
  if (/^black$/i.test(tok)) return { r: 0, g: 0, b: 0, a: 1 };
  return null;
}
function hsl({ r, g, b }) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    h = (max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4) * 60;
  }
  return { h, s, l };
}
function fromHsl(h, s, l) {
  const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l);
  const f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return { r: Math.round(f(0) * 255), g: Math.round(f(8) * 255), b: Math.round(f(4) * 255) };
}
const hex = (c) => "#" + [c.r, c.g, c.b].map((v) => v.toString(16).padStart(2, "0")).join("");
const out = (c, a) => (a >= 0.999 ? hex(c) : `rgba(${c.r},${c.g},${c.b},${+a.toFixed(3)})`);
const rgb = (h) => parse(h);
function family(c) {
  const { h, l } = hsl(c);
  // Chroma, not HSL saturation: near-white warm tones report a high saturation but read as neutral.
  const chroma = (Math.max(c.r, c.g, c.b) - Math.min(c.r, c.g, c.b)) / 255;
  if (chroma < 0.08 || l > 0.985 || l < 0.03) return "neutral";
  if (h >= 28 && h < 70) return "gold";
  if (h >= 70 && h < 175) return "green";
  if (h >= 175 && h < 265) return "blue";
  if (h >= 265 && h < 330) return "purple";
  return "red";
}

function fg(c) {
  const fam = family(c), { h, l } = hsl(c);
  if (fam === "gold") return out(l > 0.6 ? c : rgb("#e8b75a"), c.a);
  if (fam === "green") return out(fromHsl(h, 0.5, 0.72), c.a);
  if (fam === "red") return out(fromHsl(h, 0.75, 0.76), c.a);
  if (fam === "purple") return out(fromHsl(h, 0.5, 0.78), c.a);
  if (fam === "blue") return out(l > 0.6 ? c : fromHsl(h, 0.6, 0.76), c.a);
  if (l > 0.85) return out(rgb("#141414"), c.a); // light text sat on ink pills → the pills turn light
  if (l < 0.12) return out(rgb("#f2efe8"), c.a);
  if (l < 0.2) return out(rgb("#e0dcd4"), c.a);
  if (l < 0.35) return out(rgb("#c9c3b8"), c.a);
  return out(rgb("#9a948a"), c.a);
}
function surface(c, prop) {
  const fam = family(c), { h, l } = hsl(c);
  const line = /^border|^outline/.test(prop);
  if (fam !== "neutral") {
    if (l > 0.85 && c.a >= 0.6) return out(fromHsl(h, 0.28, 0.15), c.a); // pale tinted panels
    return out(c, c.a); // amber, green, red, blue fills and tints read on dark as they are
  }
  const chroma = (Math.max(c.r, c.g, c.b) - Math.min(c.r, c.g, c.b)) / 255;
  if (l < 0.3 && chroma >= 0.04) return out(c, c.a); // deep blues of the portal tile stay deep
  if (l < 0.3) return c.a < 0.6 ? out(rgb("#ffffff"), Math.min(0.16, c.a)) : out(rgb("#f2efe8"), c.a); // ink washes → light washes; ink pills → light pills
  if (line) return out(rgb("#34322f"), c.a);
  if (l > 0.82) {
    const L = clamp(0.07 + (l - 0.9) * 0.8, 0.05, 0.16);
    return out(fromHsl(40, 0.05, L), c.a);
  }
  return out(rgb("#3a3835"), c.a);
}
function shadow(c) {
  const fam = family(c), { l } = hsl(c);
  if (fam !== "neutral") return out(c, c.a);
  if (l > 0.8) return out(rgb("#ffffff"), c.a * 0.12);
  return out(rgb("#000000"), Math.min(0.6, c.a * 2.2));
}

const COLOR = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b/g;
function mapDecl(prop, value) {
  const p = prop.toLowerCase();
  let kind;
  if (/^(color|caret-color|-webkit-text-fill-color|text-decoration-color|fill|stroke|column-rule-color|accent-color)$/.test(p)) kind = "fg";
  else if (/shadow$/.test(p) || p === "filter" || p === "-webkit-filter") kind = "shadow";
  else if (/^(background|border|outline)/.test(p)) kind = "bg";
  else return null;
  // Declarations that already use tokens flip through the variables; they are still mirrored
  // unchanged so they keep their place in the cascade against the mapped rules around them.
  if (value.includes("var(")) return value;
  let changed = false;
  const next = value.replace(COLOR, (tok) => {
    const c = parse(tok);
    if (!c) return tok;
    const mapped = kind === "fg" ? fg(c) : kind === "shadow" ? shadow(c) : surface(c, p);
    if (mapped !== tok) changed = true;
    return mapped;
  });
  return changed ? next : null;
}

// ---- a small CSS walker -------------------------------------------------------
function splitTop(s, sep) {
  const parts = []; let depth = 0, start = 0, quote = null;
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (quote) { if (ch === quote) quote = null; continue; }
    if (ch === '"' || ch === "'") quote = ch;
    else if (ch === "(" || ch === "[") depth++;
    else if (ch === ")" || ch === "]") depth--;
    else if (ch === sep && depth === 0) { parts.push(s.slice(start, i)); start = i + 1; }
  }
  parts.push(s.slice(start));
  return parts;
}
function scope(selector) {
  return splitTop(selector, ",").map((raw) => {
    const s = raw.trim();
    if (!s) return s;
    if (s.startsWith(":root")) return DARK + s.slice(5);
    if (/^html\b/.test(s)) return "html[data-mode=dark]" + s.slice(4);
    return `${DARK} ${s}`;
  }).join(",");
}
function walk(css) {
  let result = "", i = 0;
  while (i < css.length) {
    const open = css.indexOf("{", i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    // find the matching close brace
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === "{") depth++; else if (css[j] === "}") depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    i = j;
    if (!head || head.startsWith("@import")) continue;
    if (/^@(font-face|keyframes|-webkit-keyframes|property|layer)\b/.test(head)) continue;
    if (head.startsWith("@")) {
      const inner = walk(body);
      if (inner) result += `${head}{${inner}}\n`;
      continue;
    }
    const decls = [];
    for (const d of splitTop(body, ";")) {
      const colon = d.indexOf(":");
      if (colon < 0) continue;
      const prop = d.slice(0, colon).trim();
      if (!prop || prop.startsWith("--")) continue;
      const mapped = mapDecl(prop, d.slice(colon + 1).trim());
      if (mapped !== null) decls.push(`${prop}:${mapped}`);
    }
    if (decls.length) result += `${scope(head)}{${decls.join(";")}}\n`;
  }
  return result;
}

// Hand-tuned after the mirrored rules, so they win: on dark, a selected pill lifts rather than sinks.
const FOOTER = `
/* hand-tuned */
${DARK} .mode-picker button[aria-checked=true]{background:#34322f;box-shadow:none}
${DARK} .entry-object figcaption{background:rgba(12,12,12,.62);color:#f6f3ec}
`;

let output = HEADER;
for (const file of SOURCES) {
  const css = fs.readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "").replace(/@import[^;]*;/g, "");
  output += `\n/* from ${file} */\n` + walk(css);
}
output += FOOTER;
fs.writeFileSync(OUT, output);
console.log(`wrote ${OUT} (${(output.length / 1024).toFixed(1)} KB)`);
